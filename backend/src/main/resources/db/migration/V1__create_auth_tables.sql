-- TNB-4 / TNB-3: customer authentication tables

CREATE TABLE customers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      VARCHAR(20)  NOT NULL UNIQUE,
    full_name        VARCHAR(100) NOT NULL,
    mobile           VARCHAR(15)  NOT NULL,
    email            VARCHAR(100) NOT NULL,
    password_hash    VARCHAR(100) NOT NULL,
    failed_attempts  INT          NOT NULL DEFAULT 0,
    locked           BOOLEAN      NOT NULL DEFAULT FALSE,
    locked_at        TIMESTAMPTZ,
    status           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_customers_failed_attempts CHECK (failed_attempts >= 0)
);

CREATE TABLE otp_challenges (
    id            UUID         PRIMARY KEY,
    customer_id   BIGINT       NOT NULL REFERENCES customers (id),
    purpose       VARCHAR(20)  NOT NULL,
    otp_hash      VARCHAR(100) NOT NULL,
    expires_at    TIMESTAMPTZ  NOT NULL,
    resend_count  INT          NOT NULL DEFAULT 0,
    used          BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_otp_challenges_customer ON otp_challenges (customer_id);

-- Simulated SMS gateway (RFP FR-NOT-01: SMS simulated in the MVP)
CREATE TABLE sms_outbox (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile   VARCHAR(15)  NOT NULL,
    message  VARCHAR(300) NOT NULL,
    sent_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_sms_outbox_mobile ON sms_outbox (mobile, sent_at DESC);

CREATE TABLE user_sessions (
    token        VARCHAR(64) PRIMARY KEY,
    customer_id  BIGINT      NOT NULL REFERENCES customers (id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at   TIMESTAMPTZ NOT NULL
);
